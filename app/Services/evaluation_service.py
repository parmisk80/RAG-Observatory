import logging
import string
import time
import uuid
from datetime import datetime, timezone
UTC = timezone.utc
from typing import Optional
import psycopg2
import psycopg2.extras
from datasets import Dataset
from psycopg2.pool import SimpleConnectionPool
from ragas import evaluate
from ragas.metrics import answer_relevancy, context_precision, faithfulness
from sentence_transformers import SentenceTransformer, util
from config.config import settings


logger = logging.getLogger(__name__)


class EvaluationService:
    """
    Initialize the evaluation service.

    Loads:
    - Embedding model used for semantic evaluation
    - PostgreSQL connection pool
    - Internal evaluation statistics

    The service supports:
    - Query rewrite evaluation
    - RAG answer evaluation
    - PostgreSQL persistence
    - Health monitoring
    """
    def __init__(self):
        self.embed_model_name = settings.EVAL_EMBED_MODEL
        self._stats = {
            "total_evaluations": 0,
            "failed_evaluations": 0,
            "avg_score": 0.0,
        }
        self._init_embed_model()
        self._init_postgres()

    """
    Load the sentence transformer model used for evaluation.

    The embedding model is required for:
    - Semantic similarity scoring
    - Retrieval gain calculation

    If loading fails, the evaluation service will continue
    running with embedding-based metrics disabled.
    """
    def _init_embed_model(self):
        try:
            self._embed_model = SentenceTransformer(self.embed_model_name)
            logger.info({
                "stage": "eval_init",
                "status": "embed_model_loaded",
                "model": self.embed_model_name,
            })
        except Exception as exc:
            logger.error(f"Embed model init failed: {exc}")
            self._embed_model = None


    def _init_postgres(self):
        """
        Initialize PostgreSQL connection pool and obtain a connection.
        """
        self._pool = None
        self._conn = None
        try:
            self._pool = SimpleConnectionPool(
                minconn = 1,
                maxconn = 10,
                dsn = settings.DATABASE_URL,
            )
            self._conn = self._pool.getconn()
            self._conn.autocommit = False
            self._create_table()
            logger.info({
                "stage":  "eval_init",
                "status": "postgres_connected",
            })
        except Exception as exc:
            logger.error(f"PostgreSQL init failed: {exc}")
            self._conn = None
            self._pool = None


    def _create_table(self):
        """
        Create the evaluations table and indexes if they do not exist.
        """
        create_table_query = """
            CREATE TABLE IF NOT EXISTS evaluations (
                id              UUID        PRIMARY KEY,
                question        TEXT        NOT NULL,
                answer          TEXT        NOT NULL,
                scores          JSONB       NOT NULL,
                timestamp       TIMESTAMP   NOT NULL DEFAULT NOW(),
                rewrite_scores  JSONB,
                rag_scores      JSONB,
                final_score     FLOAT
            );
        """
        with self._conn.cursor() as cur:
            try:
                cur.execute(create_table_query)

                cur.execute("""
                    CREATE INDEX IF NOT EXISTS idx_eval_timestamp
                    ON evaluations(timestamp)
                """)

                cur.execute("""
                    CREATE INDEX IF NOT EXISTS idx_eval_score
                    ON evaluations(final_score)
                """)

            except Exception:
                self._conn.rollback()
                raise

        self._conn.commit()

    """
    Calculate semantic similarity between two texts.

    Similarity is computed using cosine similarity
    between sentence embeddings.

    Args:
        original_query (str):
            Original user query.

        rewritten_query (str):
            Rewritten query generated by the rewrite service.

    Returns:
        float:
            Cosine similarity score between 0 and 1.
    """
    #  REWRITE EVALUATION METRICS                                     
    def semantic_similarity(
        self,
        original_query:  str,
        rewritten_query: str,
    ) -> float:

        if self._embed_model is None:
            return 0.0

        emb_orig = self._embed_model.encode(original_query,  convert_to_tensor=True)
        emb_rewrite = self._embed_model.encode(rewritten_query, convert_to_tensor=True)
        score = util.cos_sim(emb_orig, emb_rewrite).item()

        return round(float(score), 4)


    def keyword_preservation(
        self,
        original_query:  str,
        rewritten_query: str,
    ) -> float:

        stopwords = {
            "a", "an", "the", "is", "are", "was", "were",
            "what", "who", "where", "when", "how", "why",
            "do", "does", "did", "in", "on", "at", "to",
            "of", "for", "and", "or", "but",
        }
        """
        Measure keyword retention after query rewriting.

        The metric evaluates how many important keywords
        from the original query remain in the rewritten query.

        Stopwords are removed before comparison.

        Args:
            original_query (str):
                Original user query.

            rewritten_query (str):
                Rewritten query.

        Returns:
            float:
                Keyword preservation ratio between 0 and 1.
        """
        def extract_keywords(text: str) -> set:
            text = text.lower()
            text = text.translate(str.maketrans("", "", string.punctuation))
            tokens = text.split()
            return {w for w in tokens if w not in stopwords and len(w) > 2}

        original_kw  = extract_keywords(original_query)
        rewritten_kw = extract_keywords(rewritten_query)

        if not original_kw:
            return 1.0

        preserved = original_kw & rewritten_kw
        score = len(preserved) / len(original_kw)

        return round(score, 4)

    """
    Calculate query compression ratio.

    Measures how much the rewritten query differs
    in length compared to the original query.

    Args:
        original_query (str):
            Original user query.

        rewritten_query (str):
            Rewritten query.

    Returns:
        float:
            Length ratio of rewritten query to original query.
    """
    def compression_ratio(
        self,
        original_query:  str,
        rewritten_query: str,
    ) -> float:

        original_len  = len(original_query.split())
        rewritten_len = len(rewritten_query.split())

        if original_len == 0:
            return 1.0

        ratio = rewritten_len / original_len
        return round(ratio, 4)

    """
    Estimate retrieval improvement after query rewriting.

    The method compares semantic similarity between:
    - Original query and retrieved contexts
    - Rewritten query and retrieved contexts

    A positive score indicates that the rewritten query
    is more aligned with retrieved information.

    Args:
        original_query (str):
            Original query.

        rewritten_query (str):
            Rewritten query.

        contexts (list[dict]):
            Retrieved document chunks.

    Returns:
        float:
            Retrieval gain score.
    """
    def retrieval_gain(
        self,
        original_query: str,
        rewritten_query: str,
        contexts: list[dict]
    ) -> float:

        if self._embed_model is None or not contexts:
            return 0.0

        context_texts = " ".join([c.get("text", "") for c in contexts])

        sim_original  = self.semantic_similarity(original_query,  context_texts)
        sim_rewritten = self.semantic_similarity(rewritten_query, context_texts)

        gain = sim_rewritten - sim_original
        return round(gain, 4)

    """
    Evaluate query rewriting quality.

    Combines multiple rewrite metrics:

    - Semantic similarity
    - Keyword preservation
    - Compression ratio
    - Retrieval gain

    A weighted overall score is calculated
    to represent rewrite quality.

    Args:
        original_query (str):
            Original query.

        rewritten_query (str):
            Rewritten query.

        contexts (list[dict]):
            Retrieved context chunks.

    Returns:
        dict:
            Detailed rewrite evaluation results.
    """
    def evaluate_query_rewrite(
        self,
        original_query: str,
        rewritten_query: str,
        contexts: list[dict]
    ) -> dict:

        start = time.time()

        sem_sim = self.semantic_similarity(original_query, rewritten_query)
        kw_pres = self.keyword_preservation(original_query, rewritten_query)
        comp_ratio = self.compression_ratio(original_query, rewritten_query)
        ret_gain = self.retrieval_gain(original_query, rewritten_query, contexts)

        # FIX: added ndigits=4 to round()
        overall = round(
            0.4 * sem_sim +
            0.3 * kw_pres +
            0.3 * max(ret_gain + 0.5, 0.0),
            4
        )

        latency = (time.time() - start) * 1000

        logger.info({
            "stage": "rewrite_evaluation",
            "status": "success",
            "latency_ms": round(latency, 2),
            "overall": overall
        })

        return {
            "semantic_similarity": sem_sim,
            "keyword_preservation": kw_pres,
            "compression_ratio": comp_ratio,
            "retrieval_gain": ret_gain,
            "overall_rewrite_score": overall
        }

    """
    Build a RAGAS-compatible evaluation dataset.

    The dataset contains:
    - Question
    - Generated answer
    - Retrieved contexts
    - Ground truth answer

    Args:
        question (str):
            User question.

        answer (str):
            Generated answer.

        contexts (list[dict]):
            Retrieved context chunks.

        ground_truth (str):
            Expected correct answer.

    Returns:
        Dataset:
            Dataset object compatible with RAGAS.
    """
    #  RAG EVALUATION — RAGAS                                             
    def _build_dataset(
        self,
        question: str,
        answer: str,
        contexts: list[dict],
        ground_truth: str,
    ) -> Dataset:

        context_texts = [c.get("text", "") for c in contexts]

        data = {
            "question": [question],
            "answer": [answer],
            "contexts": [context_texts],
            "ground_truth": [ground_truth]
        }

        return Dataset.from_dict(data)

    """
    Execute RAGAS evaluation metrics.

    Evaluates:

    - Faithfulness
    - Answer relevancy
    - Context precision

    Args:
        dataset (Dataset):
            Evaluation dataset.

    Returns:
        dict:
            Individual RAGAS metric scores.
    """
    def _run_ragas(self, dataset: Dataset) -> dict:
        """
        Run RAGAS evaluation and extract per-metric scores correctly.
        """
        try:
            result = evaluate(
                dataset = dataset,
                metrics = [
                    faithfulness,
                    answer_relevancy,
                    context_precision,
                ]
            )

            # FIX: extract individual column values from the DataFrame
            df = result.to_pandas()
            return {
                "faithfulness": round(float(df["faithfulness"].iloc[0]),      4),
                "answer_relevancy": round(float(df["answer_relevancy"].iloc[0]),  4),
                "context_precision": round(float(df["context_precision"].iloc[0]), 4)
            }

        except Exception as exc:
            logger.error(f"RAGAS evaluation failed: {exc}")
            return {
                "faithfulness":      0.0,
                "answer_relevancy":  0.0,
                "context_precision": 0.0
            }

    """
    Evaluate RAG answer quality using RAGAS.

    The method generates a dataset,
    runs RAGAS metrics,
    and calculates an aggregated RAG score.

    Args:
        question (str):
            User question.

        answer (str):
            Generated answer.

        contexts (list[dict]):
            Retrieved context chunks.

        ground_truth (str):
            Expected answer.

    Returns:
        dict:
            RAG evaluation metrics and overall score.
    """
    def evaluate_rag(
        self,
        question: str,
        answer: str,
        contexts: list[dict],
        ground_truth: str,
    ) -> dict:

        start = time.time()

        if not contexts:
            logger.warning("No contexts provided for RAG evaluation")
            return {
                "faithfulness":      0.0,
                "answer_relevancy":  0.0,
                "context_precision": 0.0,
                "overall_rag_score": 0.0,
            }

        dataset = self._build_dataset(question, answer, contexts, ground_truth)
        ragas_scores = self._run_ragas(dataset)

        overall = round(
            0.4  * ragas_scores["faithfulness"]      +
            0.35 * ragas_scores["answer_relevancy"]  +
            0.25 * ragas_scores["context_precision"],
            4,
        )

        latency = (time.time() - start) * 1000
        logger.info({
            "stage": "rag_evaluation",
            "status": "success",
            "latency_ms": round(latency, 2),
            "overall": overall,
        })

        return {**ragas_scores, "overall_rag_score": overall}


    """
    Persist evaluation results into PostgreSQL.

    Stores:
    - Question
    - Answer
    - Rewrite metrics
    - RAG metrics
    - Final evaluation score
    - Timestamp

    Each evaluation receives a unique UUID.

    Args:
        question (str):
            User question.

        answer (str):
            Generated answer.

        rewrite_scores (dict):
            Query rewrite evaluation metrics.

        rag_scores (dict):
            RAG evaluation metrics.

        final_score (float):
            Final aggregated evaluation score.

    Returns:
        str:
            Generated evaluation UUID.
    """
    #  PERSISTENCE                                                         
    def _save_to_postgres(
        self,
        question: str,
        answer: str,
        rewrite_scores: dict,
        rag_scores: dict,
        final_score: float,
    ) -> str:

        if self._conn is None:
            logger.warning("PostgreSQL not available — skipping save")
            return ""

        evaluation_id = str(uuid.uuid4())

        query = """
            INSERT INTO evaluations
            (
                id,
                question,
                answer,
                scores,
                rewrite_scores,
                rag_scores,
                final_score,
                timestamp
            )
            VALUES
            (
                %(id)s,
                %(question)s,
                %(answer)s,
                %(scores)s,
                %(rewrite_scores)s,
                %(rag_scores)s,
                %(final_score)s,
                %(timestamp)s
            )
        """

        all_scores = {**rewrite_scores, **rag_scores}

        data = {
            "id":             evaluation_id,
            "question": question,
            "answer": answer,
            "scores": psycopg2.extras.Json(all_scores),
            "rewrite_scores": psycopg2.extras.Json(rewrite_scores),
            "rag_scores": psycopg2.extras.Json(rag_scores),
            "final_score": final_score,
            "timestamp": datetime.now(UTC),
        }

        try:
            with self._conn.cursor() as cur:
                cur.execute(query, data)
            self._conn.commit()
            return evaluation_id

        except Exception as exc:
            self._conn.rollback()
            logger.error(f"PostgreSQL save failed: {exc}")
            return ""


    """
    Generate a complete evaluation report.

    The report includes:

    - Query rewrite evaluation
    - RAG evaluation
    - Final aggregated score
    - PostgreSQL persistence
    - Evaluation metadata

    Args:
        question (str):
            User question.

        answer (str):
            Generated answer.

        contexts (list[dict]):
            Retrieved context chunks.

        ground_truth (str):
            Expected correct answer.

        original_query (Optional[str]):
            Original user query.

        rewritten_query (Optional[str]):
            Query generated by the rewrite service.

    Returns:
        dict:
            Complete evaluation report.
    """   
    #  MAIN REPORT                                                         
    def generate_evaluation_report(
        self,
        question: str,
        answer: str,
        contexts: list[dict],
        ground_truth: str,
        original_query: Optional[str] = None,
        rewritten_query: Optional[str] = None,
    ) -> dict:

        start = time.time()

        try:
            rewrite_scores = {}
            if original_query and rewritten_query:
                rewrite_scores = self.evaluate_query_rewrite(
                    original_query  = original_query,
                    rewritten_query = rewritten_query,
                    contexts = contexts
                )

            rag_scores = self.evaluate_rag(
                question = question,
                answer = answer,
                contexts = contexts,
                ground_truth = ground_truth
            )

            rag_overall = rag_scores.get("overall_rag_score",    0.0)
            rewrite_overall = rewrite_scores.get("overall_rewrite_score", 0.0)

            if rewrite_scores:
                final_score = round(0.3 * rewrite_overall + 0.7 * rag_overall, 4)
            else:
                final_score = rag_overall

            # FIX: capture the return value of _save_to_postgres
            evaluation_id = self._save_to_postgres(
                question = question,
                answer = answer,
                rewrite_scores = rewrite_scores,
                rag_scores = rag_scores,
                final_score = final_score,
            )

            latency = (time.time() - start) * 1000
            self._update_stats(success=True, final_score=final_score)

            logger.info({
                "stage": "evaluation_report",
                "status": "success",
                "latency_ms": round(latency, 2),
                "final_score": final_score,
            })

            return {
                "evaluation_id": evaluation_id,
                "question": question,
                "answer": answer,
                "final_score": final_score,
                "rewrite_evaluation": rewrite_scores,
                "rag_evaluation": rag_scores,
                "metadata": {
                    "timestamp": datetime.now(UTC).isoformat(),
                    "latency_ms": round(latency, 2),
                    "contexts_count": len(contexts),
                    "ground_truth": ground_truth,
                },
            }

        except Exception as exc:
            latency = (time.time() - start) * 1000
            self._update_stats(success=False, final_score=0.0)

            logger.error({
                "stage": "evaluation_report",
                "status": "failed",
                "message": str(exc),
            })

            return {
                "evaluation_id": None,
                "question": question,
                "answer":answer,
                "final_score": 0.0,
                "rewrite_evaluation": {},
                "rag_evaluation":{},
                "metadata": {
                    "timestamp": datetime.now(UTC).isoformat(),
                    "latency_ms": round(latency, 2),
                    "error": str(exc)
                },
            }


    """
    Perform health checks for evaluation dependencies.

    Checks:

    - RAGAS functionality
    - Embedding model availability
    - PostgreSQL connectivity

    Returns:
        dict:
            Service health status information.
    """
    #  HEALTH CHECK                                                        
    def health_check(self) -> dict:

        results = {}

        try:
            mini_dataset = Dataset.from_dict({
                "question": ["test"],
                "answer": ["test answer"],
                "contexts": [["test context"]],
                "ground_truth": ["test"],
            })
            evaluate(mini_dataset, metrics=[faithfulness])
            results["ragas"] = "healthy"
        except Exception as exc:
            results["ragas"] = f"unhealthy: {exc}"

        try:
            if self._embed_model:
                self._embed_model.encode("test")
                results["embed_model"] = "healthy"
            else:
                results["embed_model"] = "not loaded"
        except Exception as exc:
            results["embed_model"] = f"unhealthy: {exc}"

        try:
            if self._conn:
                with self._conn.cursor() as cur:
                    cur.execute("SELECT 1")
                results["postgres"] = "healthy"
            else:
                results["postgres"] = "not connected"
        except Exception as exc:
            results["postgres"] = f"unhealthy: {exc}"

        overall = "healthy" if all("unhealthy" not in str(v) for v in results.values()) else "degraded"
        results["overall"] = overall

        return results

    """
    Retrieve evaluation service statistics.

    Returns:
        dict:
            Aggregated evaluation metrics including:

            - Total evaluations
            - Failed evaluations
            - Success rate
            - Average evaluation score
    """
    #  STATS                                                               
    def get_evaluation_stats(self) -> dict:
        total  = self._stats["total_evaluations"]
        failed = self._stats["failed_evaluations"]

        return {
            "total_evaluations": total,
            "failed_evaluations": failed,
            "success_rate": round((total - failed) / max(total, 1) * 100, 2),
            "avg_score": round(self._stats["avg_score"], 4),
        }

    """
    Update internal evaluation statistics.

    Args:
        success (bool):
            Whether the evaluation completed successfully.

        final_score (float):
            Final evaluation score.
    """
    def _update_stats(self, success: bool, final_score: float):
        n = self._stats["total_evaluations"]
        self._stats["total_evaluations"] += 1
        self._stats["avg_score"] = (
            (self._stats["avg_score"] * n + final_score) / (n + 1)
        )
        if not success:
            self._stats["failed_evaluations"] += 1